#!/usr/bin/env node
/**
 * Keeps the generated i18n files in sync. Runs before `dev` and `build`.
 *
 * 1. `src/i18n/en-catalog.generated.ts` imports every `src/messages/en/*.json`
 *    namespace. It is the source of truth for message types and fallbacks.
 * 2. Every page in `src/app/[locale]/` gets a re-export in `src/app/(default)/`
 *    so the default locale (English) is served without a URL prefix.
 *
 * Usage: node scripts/i18n-sync.mjs [--check]
 *   --check  Exit with an error instead of writing when files are out of date.
 */
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const check = process.argv.includes('--check')

const messagesDir = path.join(root, 'src/messages/en')
const catalogFile = path.join(root, 'src/i18n/en-catalog.generated.ts')
const localeAppDir = path.join(root, 'src/app/[locale]')
const defaultAppDir = path.join(root, 'src/app/(default)')

const GENERATED = '// Generated by scripts/i18n-sync.mjs — do not edit.'
const PAGE_EXPORTS = [
  'default',
  'generateMetadata',
  'metadata',
  'generateStaticParams',
  'generateViewport',
  'viewport',
]

const problems = []
const changes = []

function write(file, content) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
  if (current === content) return
  changes.push(path.relative(root, file))
  if (check) return
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
}

function remove(file) {
  changes.push(`${path.relative(root, file)} (removed)`)
  if (check) return
  fs.rmSync(file)
  let dir = path.dirname(file)
  while (dir !== defaultAppDir && fs.readdirSync(dir).length === 0) {
    fs.rmdirSync(dir)
    dir = path.dirname(dir)
  }
}

function syncCatalog() {
  const namespaces = fs
    .readdirSync(messagesDir)
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort()

  for (const namespace of namespaces) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(namespace)) {
      problems.push(
        `src/messages/en/${namespace}.json: namespace names must be camelCase`,
      )
    }
    try {
      JSON.parse(fs.readFileSync(path.join(messagesDir, `${namespace}.json`)))
    } catch (error) {
      problems.push(`src/messages/en/${namespace}.json: ${error.message}`)
    }
  }

  const lines = [
    GENERATED,
    '// Lists every namespace in src/messages/en/. Run `npm run i18n:sync`.',
    '',
    ...namespaces.map(
      (namespace) =>
        `import ${namespace} from '@/messages/en/${namespace}.json'`,
    ),
    '',
    'const messages = {',
    ...namespaces.map((namespace) => `  ${namespace},`),
    '}',
    '',
    'export default messages',
    '',
  ]
  write(catalogFile, lines.join('\n'))
}

function findPages(dir, rel = '') {
  const pages = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      pages.push(
        ...findPages(path.join(dir, entry.name), path.join(rel, entry.name)),
      )
    } else if (/^page\.tsx?$/.test(entry.name)) {
      pages.push({ rel, file: path.join(dir, entry.name) })
    }
  }
  return pages
}

function exportedNames(source) {
  const names = new Set()
  if (/^export\s+default\b/m.test(source)) names.add('default')
  for (const match of source.matchAll(
    /^export\s+(?:async\s+)?(?:function|const|let)\s+(\w+)/gm,
  )) {
    names.add(match[1])
  }
  for (const match of source.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const part of match[1].split(',')) {
      const name = part
        .trim()
        .split(/\s+as\s+/)
        .pop()
      if (name) names.add(name)
    }
  }
  return names
}

function syncRoutes() {
  const sources = findPages(localeAppDir)
  const expected = new Set()

  for (const { rel, file } of sources) {
    const names = exportedNames(fs.readFileSync(file, 'utf8'))
    const segmentConfig = [...names].filter(
      (name) => !PAGE_EXPORTS.includes(name),
    )
    if (segmentConfig.length > 0) {
      problems.push(
        `${path.relative(root, file)}: exports ${segmentConfig.join(', ')}, ` +
          'which cannot be re-exported to the (default) route. ' +
          'Move route segment config to a layout or helper.',
      )
    }
    const reexports = PAGE_EXPORTS.filter((name) => names.has(name))
    const importPath = ['@/app/[locale]', rel, 'page']
      .filter(Boolean)
      .join('/')
      .replaceAll(path.sep, '/')
    const target = path.join(defaultAppDir, rel, 'page.tsx')
    expected.add(target)
    write(
      target,
      [
        GENERATED,
        '// English is served without a locale prefix, so this route re-exports',
        `// the localized page. Edit ${importPath.replace('@/', 'src/')}.tsx instead.`,
        `export { ${reexports.join(', ')} } from '${importPath}'`,
        '',
      ].join('\n'),
    )
  }

  for (const { file } of findPages(defaultAppDir)) {
    if (expected.has(file)) continue
    if (fs.readFileSync(file, 'utf8').startsWith(GENERATED)) remove(file)
  }
}

syncCatalog()
syncRoutes()

if (problems.length > 0) {
  console.error(`i18n-sync found problems:\n  ${problems.join('\n  ')}`)
  process.exit(1)
}
if (check && changes.length > 0) {
  console.error(
    `Generated i18n files are out of date. Run \`npm run i18n:sync\`:\n  ${changes.join('\n  ')}`,
  )
  process.exit(1)
}
if (!check && changes.length > 0) {
  console.log(`i18n-sync updated:\n  ${changes.join('\n  ')}`)
}
